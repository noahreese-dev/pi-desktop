const { contextBridge, ipcRenderer, webUtils } = require("electron");
const on = (ch) => (fn) => { const h = (_e, p) => fn(p); ipcRenderer.on(ch, h); return () => ipcRenderer.off(ch, h); };
contextBridge.exposeInMainWorld("desk", {
  init: () => ipcRenderer.invoke("app:init"),
  setupStatus: () => ipcRenderer.invoke("setup:status"),
  setupAddExamples: () => ipcRenderer.invoke("setup:add-examples"),
  setupReload: () => ipcRenderer.invoke("setup:reload"),
  cmd: (id, cmd) => ipcRenderer.invoke("pi:cmd", id, cmd),
  ensure: (key, harness, sessionFile) => ipcRenderer.invoke("pi:ensure", key, harness, sessionFile),
  closeChat: (key, opts) => ipcRenderer.invoke("pi:close", key, opts),
  history: (file) => ipcRenderer.invoke("chat:history", file),
  copyMarkdown: (file) => ipcRenderer.invoke("chat:copy-markdown", file),
  permStatus: () => ipcRenderer.invoke("perm:status"),
  permOpen: (kind) => ipcRenderer.invoke("perm:open", kind),
  running: () => ipcRenderer.invoke("pi:running"),
  restart: (id) => ipcRenderer.invoke("pi:restart", id),
  uiResponse: (id, resp) => ipcRenderer.send("pi:ui-response", id, resp),
  sessions: (id) => ipcRenderer.invoke("sessions:list", id),
  topics: (root) => ipcRenderer.invoke("learn:topics", root),
  read: (p) => ipcRenderer.invoke("fs:read", p),
  list: (dir) => ipcRenderer.invoke("fs:list", dir),
  reveal: (p) => ipcRenderer.invoke("fs:reveal", p),
  open: (p) => ipcRenderer.invoke("fs:open", p),
  allowed: (p) => ipcRenderer.invoke("fs:allowed", p),
  transcribe: (bytes, before) => ipcRenderer.invoke("voice:transcribe", bytes, before),
  voiceWarm: () => ipcRenderer.invoke("voice:warm"),
  micPermission: () => ipcRenderer.invoke("voice:permission"),
  setCharacter: (id) => ipcRenderer.send("app:character", id),
  tasks: () => ipcRenderer.invoke("tasks:list"),
  saveTask: (t) => ipcRenderer.invoke("tasks:save", t),
  deleteTask: (id) => ipcRenderer.invoke("tasks:delete", id),
  runTask: (id) => ipcRenderer.invoke("tasks:run", id),
  stopTask: (id) => ipcRenderer.invoke("tasks:stop", id),
  onTasks: on("tasks:update"),
  onOpenTask: on("app:open-task"),
  topic: (p) => ipcRenderer.invoke("learn:topic", p),
  threadMeta: (file, patch) => ipcRenderer.invoke("threads:meta", file, patch),
  trashThread: (file) => ipcRenderer.invoke("threads:trash", file),
  config: () => ipcRenderer.invoke("app:config"),
  saveConfig: (patch) => ipcRenderer.invoke("app:save-config", patch),
  badge: (n) => ipcRenderer.invoke("app:badge", n),
  pickFiles: () => ipcRenderer.invoke("app:open-paths"),
  readImage: (p) => ipcRenderer.invoke("fs:read-image", p),
  openExport: (p) => ipcRenderer.invoke("app:open-export", p),
  mem: (method, sub, body) => ipcRenderer.invoke("mem:req", method, sub, body),
  onMenu: on("app:menu"),
  usage: () => ipcRenderer.invoke("usage:get"),
  bumpUsage: (id) => ipcRenderer.invoke("usage:bump", id),
  previewFinish: (harness) => ipcRenderer.invoke("sound:preview", harness),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return ""; } },
  onEvent: on("pi:event"),
  onExit: on("pi:exit"),
  onLesson: on("learn:lesson"),
  onFocusCharacter: on("app:focus-character"),
  onFocusChat: on("app:focus-chat"),
});
